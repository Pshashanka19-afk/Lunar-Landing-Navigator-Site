import { IEphemerisProvider } from '../ephemeris/ephemeris.interface';
import { IDemProvider } from '../terrain/dem.interface';
import { WindowCalculationService } from '../windows/window-calculation.service';
import { SurfaceNormalService } from '../terrain/surface-normal.service';
import { roundToPrecision } from '../../utils/units';
import { ScientificValidationError } from '../../types/errors';

export interface CandidateSiteInput {
  id: string;
  name: string;
  latitudeDeg: number;
  longitudeDeg: number;
  elevationMeters?: number;
}

export interface MissionRequirements {
  minSunlightHours?: number;
  minContinuousSunlightHours?: number;
  minEarthVisibilityHours?: number;
  minSimultaneousSunEarthHours?: number;
  maxSlopeDeg?: number;
  minTerrainCompletenessPercentage?: number;
  weights?: {
    sunlightDuration?: number;
    continuousSunlight?: number;
    earthVisibility?: number;
    slopeFlatness?: number;
  };
}

export interface RequirementCheck {
  requirementName: string;
  requiredValue: number;
  actualValue: number;
  unit: string;
  status: 'PASS' | 'FAIL' | 'UNKNOWN';
  details: string;
}

export interface SiteComparisonItem {
  site: CandidateSiteInput;
  metrics: {
    slopeDeg: number;
    elevationMeters: number;
    aspectDeg: number;
    sunlightTotalHours: number;
    longestSunlightContinuousHours: number;
    earthVisibilityTotalHours: number;
    longestEarthContinuousHours: number;
    bothVisibilityTotalHours: number;
  };
  requirementChecks: RequirementCheck[];
  overallStatus: 'ALL_PASSED' | 'CONSTRAINTS_VIOLATED' | 'INCOMPLETE_DATA';
  score?: number; // 0 - 100
  scoreBreakdown?: Record<string, number>;
  reasons: string[];
  limitations: string[];
}

export interface SiteComparisonResult {
  interval: {
    startUtc: string;
    endUtc: string;
    durationHours: number;
  };
  requirementsApplied: MissionRequirements;
  sites: SiteComparisonItem[];
  ranking: string[]; // site IDs ordered by score or compliance
  disclaimer: string;
}

export class SiteScoringService {
  public static readonly DISCLAIMER =
    'This report is generated by a scientific decision-support system. It does not certify landing safety, hazard avoidance, terrain trafficability, or flight readiness.';

  /**
   * Compares multiple candidate lunar landing sites against defined mission requirements.
   */
  public static async compareSites(
    ephemerisProvider: IEphemerisProvider,
    demProvider: IDemProvider,
    sites: CandidateSiteInput[],
    requirements: MissionRequirements,
    startTimeUtc: string,
    endTimeUtc: string,
    stepSeconds = 600
  ): Promise<SiteComparisonResult> {
    if (!sites || sites.length === 0) {
      throw new ScientificValidationError('At least one candidate site must be provided for comparison');
    }

    const comparedSites: SiteComparisonItem[] = [];

    for (const site of sites) {
      // 1. Compute surface slope and terrain orientation
      const surface = await SurfaceNormalService.analyzeSurface(demProvider, {
        latitudeDeg: site.latitudeDeg,
        longitudeDeg: site.longitudeDeg,
      });

      // 2. Compute time windows over interval
      const windows = await WindowCalculationService.calculateWindows(ephemerisProvider, demProvider, {
        siteCoords: {
          latitudeDeg: site.latitudeDeg,
          longitudeDeg: site.longitudeDeg,
          elevationMeters: site.elevationMeters ?? surface.elevationMeters,
        },
        startTimeUtc,
        endTimeUtc,
        stepSeconds,
        includeTimeSeries: false,
      });

      const checks: RequirementCheck[] = [];
      const reasons: string[] = [];

      // Check minSunlightHours
      if (requirements.minSunlightHours !== undefined) {
        const passed = windows.summary.sunlightTotalHours >= requirements.minSunlightHours;
        checks.push({
          requirementName: 'Minimum Sunlight Duration',
          requiredValue: requirements.minSunlightHours,
          actualValue: windows.summary.sunlightTotalHours,
          unit: 'hours',
          status: passed ? 'PASS' : 'FAIL',
          details: passed
            ? `Site provides ${windows.summary.sunlightTotalHours}h of sunlight, meeting >= ${requirements.minSunlightHours}h`
            : `Site provides only ${windows.summary.sunlightTotalHours}h of sunlight, below requirement of ${requirements.minSunlightHours}h`,
        });
        if (!passed) reasons.push(`Insufficient total sunlight duration (${windows.summary.sunlightTotalHours}h < ${requirements.minSunlightHours}h)`);
      }

      // Check minContinuousSunlightHours
      if (requirements.minContinuousSunlightHours !== undefined) {
        const passed =
          windows.summary.longestSunlightContinuousHours >= requirements.minContinuousSunlightHours;
        checks.push({
          requirementName: 'Minimum Continuous Sunlight',
          requiredValue: requirements.minContinuousSunlightHours,
          actualValue: windows.summary.longestSunlightContinuousHours,
          unit: 'hours',
          status: passed ? 'PASS' : 'FAIL',
          details: passed
            ? `Longest continuous sunlight is ${windows.summary.longestSunlightContinuousHours}h, meeting >= ${requirements.minContinuousSunlightHours}h`
            : `Longest continuous sunlight is only ${windows.summary.longestSunlightContinuousHours}h, below requirement of ${requirements.minContinuousSunlightHours}h`,
        });
        if (!passed) reasons.push(`Continuous sunlight window too short (${windows.summary.longestSunlightContinuousHours}h < ${requirements.minContinuousSunlightHours}h)`);
      }

      // Check minEarthVisibilityHours
      if (requirements.minEarthVisibilityHours !== undefined) {
        const passed =
          windows.summary.earthVisibilityTotalHours >= requirements.minEarthVisibilityHours;
        checks.push({
          requirementName: 'Minimum Earth Visibility',
          requiredValue: requirements.minEarthVisibilityHours,
          actualValue: windows.summary.earthVisibilityTotalHours,
          unit: 'hours',
          status: passed ? 'PASS' : 'FAIL',
          details: passed
            ? `Earth visibility is ${windows.summary.earthVisibilityTotalHours}h, meeting >= ${requirements.minEarthVisibilityHours}h`
            : `Earth visibility is only ${windows.summary.earthVisibilityTotalHours}h, below requirement of ${requirements.minEarthVisibilityHours}h`,
        });
        if (!passed) reasons.push(`Insufficient Earth visibility (${windows.summary.earthVisibilityTotalHours}h < ${requirements.minEarthVisibilityHours}h)`);
      }

      // Check minSimultaneousSunEarthHours
      if (requirements.minSimultaneousSunEarthHours !== undefined) {
        const passed =
          windows.summary.bothVisibilityTotalHours >= requirements.minSimultaneousSunEarthHours;
        checks.push({
          requirementName: 'Minimum Simultaneous Sun/Earth Visibility',
          requiredValue: requirements.minSimultaneousSunEarthHours,
          actualValue: windows.summary.bothVisibilityTotalHours,
          unit: 'hours',
          status: passed ? 'PASS' : 'FAIL',
          details: passed
            ? `Simultaneous Sun/Earth visibility is ${windows.summary.bothVisibilityTotalHours}h, meeting >= ${requirements.minSimultaneousSunEarthHours}h`
            : `Simultaneous Sun/Earth visibility is only ${windows.summary.bothVisibilityTotalHours}h, below requirement of ${requirements.minSimultaneousSunEarthHours}h`,
        });
        if (!passed) reasons.push(`Insufficient simultaneous Sun & Earth visibility (${windows.summary.bothVisibilityTotalHours}h < ${requirements.minSimultaneousSunEarthHours}h)`);
      }

      // Check maxSlopeDeg
      if (requirements.maxSlopeDeg !== undefined) {
        const passed = surface.slopeDeg <= requirements.maxSlopeDeg;
        checks.push({
          requirementName: 'Maximum Slope Angle',
          requiredValue: requirements.maxSlopeDeg,
          actualValue: roundToPrecision(surface.slopeDeg, 2),
          unit: 'degrees',
          status: passed ? 'PASS' : 'FAIL',
          details: passed
            ? `Slope is ${surface.slopeDeg.toFixed(2)}°, within allowable limit of <= ${requirements.maxSlopeDeg}°`
            : `Slope is ${surface.slopeDeg.toFixed(2)}°, exceeding limit of ${requirements.maxSlopeDeg}°`,
        });
        if (!passed) reasons.push(`Terrain slope too steep (${surface.slopeDeg.toFixed(2)}° > ${requirements.maxSlopeDeg}°)`);
      }

      const anyFailed = checks.some((c) => c.status === 'FAIL');
      const overallStatus = anyFailed ? 'CONSTRAINTS_VIOLATED' : 'ALL_PASSED';

      // Scoring if weights are provided
      let score: number | undefined;
      let scoreBreakdown: Record<string, number> | undefined;

      if (requirements.weights) {
        const wSun = requirements.weights.sunlightDuration ?? 25;
        const wCont = requirements.weights.continuousSunlight ?? 25;
        const wEarth = requirements.weights.earthVisibility ?? 25;
        const wSlope = requirements.weights.slopeFlatness ?? 25;
        const totalWeight = wSun + wCont + wEarth + wSlope;

        if (totalWeight > 0) {
          const missionHours = windows.missionInterval.totalDurationHours;
          const sunNorm = Math.min(1.0, windows.summary.sunlightTotalHours / missionHours);
          const contNorm = Math.min(1.0, windows.summary.longestSunlightContinuousHours / missionHours);
          const earthNorm = Math.min(1.0, windows.summary.earthVisibilityTotalHours / missionHours);
          // Slope score: 0 slope = 1.0, slope >= 25 deg = 0.0
          const slopeNorm = Math.max(0.0, 1.0 - surface.slopeDeg / 25.0);

          const rawScore =
            (sunNorm * wSun + contNorm * wCont + earthNorm * wEarth + slopeNorm * wSlope) /
            totalWeight;

          score = roundToPrecision(rawScore * 100.0, 2);
          scoreBreakdown = {
            sunlightDurationScore: roundToPrecision(sunNorm * 100, 2),
            continuousSunlightScore: roundToPrecision(contNorm * 100, 2),
            earthVisibilityScore: roundToPrecision(earthNorm * 100, 2),
            slopeFlatnessScore: roundToPrecision(slopeNorm * 100, 2),
          };
        }
      }

      comparedSites.push({
        site,
        metrics: {
          slopeDeg: roundToPrecision(surface.slopeDeg, 2),
          elevationMeters: roundToPrecision(surface.elevationMeters, 1),
          aspectDeg: roundToPrecision(surface.aspectDeg, 2),
          sunlightTotalHours: windows.summary.sunlightTotalHours,
          longestSunlightContinuousHours: windows.summary.longestSunlightContinuousHours,
          earthVisibilityTotalHours: windows.summary.earthVisibilityTotalHours,
          longestEarthContinuousHours: windows.summary.longestEarthVisibilityContinuousHours,
          bothVisibilityTotalHours: windows.summary.bothVisibilityTotalHours,
        },
        requirementChecks: checks,
        overallStatus,
        score,
        scoreBreakdown,
        reasons,
        limitations: [
          'Calculations use point-source geometric solar illumination',
          'Earth visibility denotes line-of-sight geometry without radio link budget margins',
          'Local slope computed over configured DEM resolution',
        ],
      });
    }

    // Sort ranking: sites with higher scores first; if no score, pass sites first
    const sorted = [...comparedSites].sort((a, b) => {
      if (a.score !== undefined && b.score !== undefined) {
        return b.score - a.score;
      }
      if (a.overallStatus === 'ALL_PASSED' && b.overallStatus !== 'ALL_PASSED') return -1;
      if (b.overallStatus === 'ALL_PASSED' && a.overallStatus !== 'ALL_PASSED') return 1;
      return 0;
    });

    const totalDurationHours = roundToPrecision(
      (new Date(endTimeUtc).getTime() - new Date(startTimeUtc).getTime()) / 3600000.0,
      4
    );

    return {
      interval: {
        startUtc: startTimeUtc,
        endUtc: endTimeUtc,
        durationHours: totalDurationHours,
      },
      requirementsApplied: requirements,
      sites: comparedSites,
      ranking: sorted.map((s) => s.site.id),
      disclaimer: this.DISCLAIMER,
    };
  }
}
